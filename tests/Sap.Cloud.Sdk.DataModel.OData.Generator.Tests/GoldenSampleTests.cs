using Sap.Cloud.Sdk.DataModel.OData.Generator.Tests.Support;

namespace Sap.Cloud.Sdk.DataModel.OData.Generator.Tests;

/// <summary>
/// The generated sample of the runtime library tests (<c>tests/Sap.Cloud.Sdk.DataModel.OData.Core.Tests/Sample</c>) is the output of the
/// generator for <c>SDK_Grocery_Store.edmx</c>. These tests make sure the checked-in files are exactly what the generator produces.
/// </summary>
/// <remarks>
/// To update the sample after a deliberate change of the generator, run the tests with the environment variable
/// <c>SAP_SDK_UPDATE_GOLDEN=1</c>: the sample files are rewritten and the test then passes.
/// </remarks>
public class GoldenSampleTests
{
    private static async Task<string> GenerateSampleAsync()
    {
        var edmx = Path.Combine(Harness.SampleDirectory, "SDK_Grocery_Store.edmx");
        var mappings = Path.Combine(Harness.TestData, "Golden", "serviceNameMappings.properties");
        var (result, output) = await Harness.GenerateAsync(
            edmx,
            options =>
            {
                options.RootNamespace = Harness.SampleRootNamespace;
                options.NameSource = NameSource.Name;
                options.DefaultBasePath = "/";
            },
            mappings);
        Assert.Empty(result.Warnings);
        Assert.Equal(ServiceGenerationStatus.Generated, Assert.Single(result.Services).Status);
        return output;
    }

    private static Dictionary<string, string> ReadFiles(string directory, bool sampleOnly) =>
        Directory
            .EnumerateFiles(directory, "*.cs", SearchOption.AllDirectories)
            .Where(f => !sampleOnly || IsGeneratedPath(directory, f))
            .ToDictionary(f => Path.GetRelativePath(directory, f).Replace('\\', '/'), File.ReadAllText, StringComparer.Ordinal);

    private static bool IsGeneratedPath(string root, string file)
    {
        var relative = Path.GetRelativePath(root, file).Replace('\\', '/');
        return relative.StartsWith("Namespaces/", StringComparison.Ordinal) || relative.StartsWith("Services/", StringComparison.Ordinal);
    }

    [Fact]
    public async Task Sample_IsReproducedByteForByte()
    {
        var output = await GenerateSampleAsync();
        var generated = ReadFiles(output, sampleOnly: false);
        var sampleDirectory = Harness.SampleDirectory;

        if (Environment.GetEnvironmentVariable("SAP_SDK_UPDATE_GOLDEN") == "1")
        {
            foreach (var directory in new[] { "Namespaces", "Services" })
            {
                var path = Path.Combine(sampleDirectory, directory);
                if (Directory.Exists(path))
                {
                    Directory.Delete(path, recursive: true);
                }
            }
            foreach (var (relative, content) in generated)
            {
                var path = Path.Combine(sampleDirectory, relative);
                Directory.CreateDirectory(Path.GetDirectoryName(path)!);
                File.WriteAllText(path, content, new System.Text.UTF8Encoding(false));
            }
        }

        var checkedIn = ReadFiles(sampleDirectory, sampleOnly: true);
        Assert.Equal(generated.Keys.Order(StringComparer.Ordinal), checkedIn.Keys.Order(StringComparer.Ordinal));
        foreach (var (relative, content) in generated)
        {
            Assert.True(content == checkedIn[relative], $"The checked-in sample file {relative} differs from the generator output. Run the tests with SAP_SDK_UPDATE_GOLDEN=1 to update it.");
        }
    }

    [Fact]
    public async Task GeneratedFiles_UseUnixNewlinesAndNoByteOrderMark()
    {
        var output = await GenerateSampleAsync();
        foreach (var file in Directory.EnumerateFiles(output, "*.cs", SearchOption.AllDirectories))
        {
            var bytes = await File.ReadAllBytesAsync(file);
            Assert.False(bytes.Length >= 3 && bytes[0] == 0xEF && bytes[1] == 0xBB && bytes[2] == 0xBF, file);
            Assert.DoesNotContain((byte)'\r', bytes);
            Assert.Equal((byte)'\n', bytes[^1]);
            var text = System.Text.Encoding.UTF8.GetString(bytes);
            Assert.StartsWith("// <auto-generated/>\n#nullable enable\n", text, StringComparison.Ordinal);
            Assert.DoesNotContain(" \n", text, StringComparison.Ordinal);
        }
    }

    [Fact]
    public async Task Output_IsDeterministic()
    {
        var first = ReadFiles(await GenerateSampleAsync(), sampleOnly: false);
        var second = ReadFiles(await GenerateSampleAsync(), sampleOnly: false);
        Assert.Equal(first, second);
    }

    [Fact]
    public async Task Sample_CompilesWithoutDiagnostics()
    {
        var diagnostics = Harness.Compile(await GenerateSampleAsync());
        Assert.True(diagnostics.Count == 0, Harness.Describe(diagnostics));
    }
}
