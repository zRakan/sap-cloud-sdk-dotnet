namespace Sap.Cloud.Sdk.DataModel.OData.Generator;

/// <summary>What the emitters need besides the model of a service: the options and the file preamble.</summary>
internal sealed class EmitContext(GenService service, ODataGeneratorOptions options)
{
    internal const string GeneratorReference = "// Generated by the SAP Cloud SDK for .NET OData V2 generator.";

    internal GenService Service { get; } = service;

    internal ODataGeneratorOptions Options { get; } = options;

    /// <summary>The namespaces of the runtime library used by generated entity and complex type files.</summary>
    internal static readonly string[] EntityUsings =
    [
        "System",
        "System.Collections.Generic",
        "System.Linq",
        "System.Threading",
        "System.Threading.Tasks",
        "Sap.Cloud.Sdk.DataModel.OData.Adapter",
        "Sap.Cloud.Sdk.DataModel.OData.Annotation",
        "Sap.Cloud.Sdk.DataModel.OData.Helper",
    ];

    /// <summary>Starts a file: auto-generated marker, header, nullable context, usings and the file-scoped namespace.</summary>
    internal CodeWriter StartFile(IEnumerable<string> usings, string ns)
    {
        var writer = new CodeWriter();
        writer.Line("// <auto-generated/>");
        WriteHeader(writer);
        if (Options.GenerateVersionReference)
        {
            writer.Line(GeneratorReference);
        }
        writer.Line("#nullable enable");
        if (Service.IsDeprecated)
        {
            writer.Line("#pragma warning disable CS0618 // The service is deprecated; its generated classes refer to each other.");
        }
        writer.Blank();
        CSharp.Usings(writer, usings);
        writer.Blank();
        writer.Line($"namespace {ns};");
        writer.Blank();
        return writer;
    }

    private void WriteHeader(CodeWriter writer)
    {
        if (string.IsNullOrWhiteSpace(Options.FileHeader))
        {
            return;
        }
        var header = Options.FileHeader.ReplaceLineEndings("\n").TrimEnd('\n');
        if (header.TrimStart().StartsWith("/*", StringComparison.Ordinal))
        {
            foreach (var line in header.Split('\n'))
            {
                writer.Line(line.TrimEnd());
            }
            return;
        }
        foreach (var line in header.Split('\n'))
        {
            var trimmed = line.TrimEnd();
            writer.Line(trimmed.TrimStart().StartsWith("//", StringComparison.Ordinal) ? trimmed.TrimStart() : trimmed.Length == 0 ? "//" : "// " + trimmed);
        }
    }
}
